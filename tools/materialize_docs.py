"""Materialize root artifacts from the canonical docs (docs tooling, not bot code).

Generated files:

* ``AGENTS.md``: copy of ``docs/build-silverbot.md`` with a banner.
* ``MODEL_CARD.md``: section 1 of ``docs/aia-silverbot.md`` with a banner.
* ``BRAND.md`` and ``DESIGN.md``: sections 0-1 and 2-7 of ``docs/dsd-silverbot.md``
  with a banner.
* ``.claude/agents/*.md``: the four-backtick ``markdown`` agent cards in
  ``docs/sad-silverbot.md``.

Usage (from the repository root)::

    python tools/materialize_docs.py            # write any out-of-date files
    python tools/materialize_docs.py --check    # exit 1 if any file is out of date

The repository root defaults to the parent of ``tools/``. Edit the canonical doc,
never the generated file. Uses only the Python standard library.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

DEFAULT_ROOT = Path(__file__).resolve().parent.parent
BANNER = ("> Materialized from `{src}`. Do not edit this file directly; "
          "edit the canonical doc and re-materialize with "
          "`python tools/materialize_docs.py`.\n\n")
LINK_RE = re.compile(r"\[([^\]]*)\]\(([^)\s]+)\)")
CARD_RE = re.compile(
    r"\*\*Materializes to:\*\* `(\.claude/agents/[a-z0-9-]+\.md)`\s*\n+````markdown\n(.*?)\n````",
    re.S,
)


def to_root_links(text: str) -> str:
    """Rewrite links written relative to docs/ so they resolve from the repo root."""
    def fix(m: re.Match[str]) -> str:
        label, target = m.group(1), m.group(2)
        if re.match(r"(https?:|mailto:|#|/)", target):
            return m.group(0)
        new = target[3:] if target.startswith("../") else f"docs/{target}"
        return f"[{label}]({new})"
    return LINK_RE.sub(fix, text)


def section(text: str, heading: str) -> str:
    """Return the text from ``heading`` up to, not including, the next ``## `` line."""
    start = text.index(heading)
    nxt = re.search(r"^## ", text[start + len(heading):], re.M)
    end = start + len(heading) + nxt.start() if nxt else len(text)
    return text[start:end].rstrip() + "\n"


def span(text: str, first: str, stop: str) -> str:
    """Return the text from heading ``first`` up to, not including, heading ``stop``."""
    start = text.index(first)
    return text[start:text.index(stop, start)].rstrip() + "\n"


def targets(root: Path) -> dict[str, str]:
    """Build the expected content of every generated file, keyed by relative path."""
    def read(rel: str) -> str:
        return (root / rel).read_text(encoding="utf-8")

    out: dict[str, str] = {}
    build = read("docs/build-silverbot.md")
    out["AGENTS.md"] = BANNER.format(src="docs/build-silverbot.md") + to_root_links(build)
    aia = read("docs/aia-silverbot.md")
    card = section(aia, "## 1. Model / System Card")
    out["MODEL_CARD.md"] = (BANNER.format(src="docs/aia-silverbot.md §1")
                            + "# Model Card: Silver Bot ML Filter\n\n" + to_root_links(card))
    dsd = read("docs/dsd-silverbot.md")
    note = "Section references (§) point to `docs/dsd-silverbot.md`.\n\n"
    out["BRAND.md"] = (BANNER.format(src="docs/dsd-silverbot.md §0-1")
                       + "# Brand: Silverbot\n\n" + note
                       + to_root_links(span(dsd, "## 0. Brand Stance", "## 2. ")))
    out["DESIGN.md"] = (BANNER.format(src="docs/dsd-silverbot.md §2-7")
                        + "# Design System: Silverbot\n\n" + note
                        + to_root_links(span(dsd, "## 2. ", "## 8. ")))
    sad = read("docs/sad-silverbot.md")
    for path, body in CARD_RE.findall(sad):
        out[path] = body.rstrip() + "\n"
    return out


def main(argv: list[str] | None = None) -> int:
    """Write (or with ``--check`` verify) the generated files. Returns the exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("root", nargs="?", type=Path, default=DEFAULT_ROOT,
                        help="repository root (default: parent of tools/)")
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if any generated file is out of date")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    diffs: list[str] = []
    for rel, content in targets(root).items():
        dest = root / rel
        current = dest.read_text(encoding="utf-8") if dest.exists() else None
        if current != content:
            diffs.append(rel)
            if not args.check:
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(content, encoding="utf-8", newline="\n")
    if args.check and diffs:
        print("out of date: " + ", ".join(diffs))
        return 1
    print("materialized: " + (", ".join(diffs) if diffs else "no changes"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
